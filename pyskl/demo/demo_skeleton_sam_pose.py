def load_video_metadata(meta_path: str) -> Dict[int, Dict]:
    """
    Load video metadata from JSON file.
    
    Args:
        meta_path: Path to video_meta.json
        
    Returns:
        Dictionary mapping row_idx to video metadata record
    """
    with open(meta_path, 'r') as f:
        data = json.load(f)
    
    # Build lookup by row_idx
    lookup = {rec['row_idx']: rec for rec in data['records']}
    return lookup


def get_video_info_from_row(row_idx: int, meta_lookup: Dict[int, Dict]) -> Optional[Dict]:
    """
    Get video information for a given row index.
    
    Args:
        row_idx: Row index (1-based)
        meta_lookup: Video metadata lookup dictionary
        
    Returns:
        Video metadata record or None if not found
    """
    if row_idx not in meta_lookup:
        return None
    return meta_lookup[row_idx]


